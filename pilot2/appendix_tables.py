# ---------------------------------------------------------------- A11 canary-split draws
DRAWS = [("human_real3", "human3_matched.md", "1234"),
         ("human_ds2345", "human_ds_matched.md", "2345"),
         ("human_ds3456", "human_ds_matched.md", "3456"),
         ("human_ds4567", "human_ds_matched.md", "4567")]


def _matched(path: Path, tier: str):
    """{model: (excess, extraction)} from the last matched-loss column of one report."""
    out, section = {}, None
    for line in path.read_text(encoding="utf-8").split("\n"):
        if line.startswith("## "):
            section = line
            continue
        if not line.startswith("| ") or "---" in line or "model |" in line:
            continue
        if section is None or f"planted {tier}" not in section:
            continue
        c = [x.strip() for x in line.strip("|").split("|")]
        m = re.match(r"([\d.]+)\s*\(([\d.]+)\)", c[-1])
        if m:
            out[c[0]] = (float(m.group(1)), float(m.group(2)))
    return out


def table_draws(res: Path, out: Path):
    """The same measurement under four different member/non-member splits."""
    per_draw = {}
    no_range = []
    for d, fname, seed in DRAWS:
        p = res / d / fname
        if not p.exists():
            continue
        if "No common range" in p.read_text(encoding="utf-8"):
            no_range.append(seed)
            continue
        per_draw[seed] = (_matched(p, "1x"), _matched(p, "16x"))
    if not per_draw:
        print("  (no matched reports for the draws)")
        return
    models = []
    for one, _ in per_draw.values():
        for m in one:
            if m not in models:
                models.append(m)
    seeds = list(per_draw)
    lines = [head("A11: the four canary-split draws."),
             "\\begin{tabular}{l" + "c" * (2 * len(seeds)) + "}", "\\toprule",
             "& \\multicolumn{%d}{c}{1 copy} & \\multicolumn{%d}{c}{16 copies} \\\\"
             % (len(seeds), len(seeds)),
             "\\cmidrule(lr){2-%d}\\cmidrule(lr){%d-%d}"
             % (1 + len(seeds), 2 + len(seeds), 1 + 2 * len(seeds)),
             "model & " + " & ".join([f"seed {s}" for s in seeds] * 2) + " \\\\", "\\midrule"]
    for m in models:
        cells = []
        for tier in (0, 1):
            for s in seeds:
                v = per_draw[s][tier].get(m)
                cells.append("---" if v is None else f"{v[0]:.2f}")
        lines.append(esc(m) + " & " + " & ".join(cells) + " \\\\")
    if no_range:
        lines.append("\\midrule")
        lines.append("\\multicolumn{%d}{l}{\\footnotesize Draw %s has no matched comparison: "
                     "its models' overfitting branches do not overlap.} \\\\"
                     % (1 + 2 * len(seeds), ", ".join(no_range)))
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "t_draws.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"  t_draws.tex ({len(models)} models x {len(seeds)} draws)")


