"""The appendix's data tables, written from the published measurements.

    python -m pilot2.appendix_tables --results results --out paper/tables

Every range the main text quotes -- 0.92--0.96, 8/8/14\\%, 0.21--0.39 -- is a summary of cells that
exist as files. The appendix exists to show those cells, and transcribing them by hand is how a
paper ends up with a number no file supports. So the appendix's tables are generated: this writes
one `.tex` file per table, each a bare `tabular` that `appendix.tex` wraps in a float with its own
caption, and each regenerated from `results/figure_data.csv` and the reports beside it.

  A4  per-seed DNABERT-2 chromosome-22 cells behind Table 3 of the main text
  A5  the tokenizer sweep at matched held-out loss, per seed, at both window lengths
  A6  the six downstream tasks, per model, at three points of each run
  A7  the nineteen single-basis chromosome-22 cells of 23 Oct, as measured

Nothing here rounds differently from the main text: the same interpolation function reads the same
columns, so a mismatch between an appendix cell and a main-text range is a real disagreement and not
a formatting artefact.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path

TARGETS = (2.05, 2.10, 2.20, 2.40)
TOKS = ["char", "2mer", "3mer", "4mer", "5mer", "6mer"]
SLOTS = {"char": 48, "2mer": 24, "3mer": 16, "4mer": 12, "5mer": 9.6, "6mer": 8}
TOKLAB = {"char": "char", "2mer": "\\kmer{2}", "3mer": "\\kmer{3}", "4mer": "\\kmer{4}",
          "5mer": "\\kmer{5}", "6mer": "\\kmer{6}"}
EPOCH_ORDER = {"15": 15, "30": 30, "50": 50, "80": 80, "120": 120, "final": 150}
TASKS = ["promoter", "core prom.", "TF binding", "splice", "H3", "H3K4me3"]


def head(note: str) -> str:
    return f"% Generated by pilot2/appendix_tables.py -- do not edit. {note}\n"


# ---------------------------------------------------------------- shared readers
def load(res: Path):
    return list(csv.DictReader(open(res / "figure_data.csv", encoding="utf-8")))


def cell(rows, group, run, tier, host, epoch, field):
    for r in rows:
        if (r["group"] == group and r["run"] == run and r["tier"] == tier
                and r["host"] == host and r["epoch"] == epoch):
            return float(r[field])
    return None


def esc(s: str) -> str:
    """A cell read out of a report, made safe for LaTeX. A bare % would eat the rest of the row."""
    return str(s).replace("\\", "/").replace("%", "\\%").replace("_", "\\_").replace("&", "\\&")


def pct(x):
    return "---" if x is None else f"{100 * x:.0f}\\%"


def two(x):
    return "---" if x is None else f"{x:.2f}"


# ---------------------------------------------------------------- A4
def table_ident(rows, out: Path, res: Path):
    """Every DNABERT-2 chromosome-22 cell, per seed: what the main text gives as three numbers.

    Rewritten 27 Oct. The previous version had two faults the pre-submission panel found.

    It had no fresh-host column, so the main text's headline range -- single-copy identification
    in a window the model never saw, 0.18--0.26 -- had no per-seed table behind it anywhere in
    the paper, which is the one thing this appendix exists to provide.

    And its control row read "0 in all 18 cells, 300 segments", which was written by hand and is
    false: results/borrowed_host.json has rank-1 hits among the never-trained probes. Both
    control rows are now read out of that file like every other cell here, and the row says which
    cells are non-zero instead of asserting that none are.
    """
    bh = json.loads((res / "borrowed_host.json").read_text(encoding="utf-8"))
    by_ck = {r["checkpoint"]: r for r in bh["rows"]}
    runs = [f"dnabert2bpe_human_s{s}" for s in (0, 1, 2)]
    eps = sorted({r["epoch"] for r in rows if r["group"] == "bpe_human"}, key=lambda e: EPOCH_ORDER[e])
    lines = [head("A4: per-seed DNABERT-2 on chromosome 22, both host conditions, both controls."),
             "\\begin{tabular}{llcccccccc}", "\\toprule",
             "& & & \\multicolumn{1}{c}{16 copies} & \\multicolumn{2}{c}{1 copy, id} & "
             "\\multicolumn{2}{c}{control, id} & \\multicolumn{2}{c}{verbatim} \\\\",
             "\\cmidrule(lr){4-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}",
             "checkpoint & seed & \\bits & id & own & fresh & own & fresh & 16 & 1 \\\\",
             "\\midrule"]

    def bhcell(e, key, i):
        row = by_ck.get("ep" + e if e != "final" else "final")
        if not row or key not in row["cells"]:
            return None
        v = row["cells"][key]["rate"]
        return v[i] if i < len(v) and v[i] is not None else None

    nonzero = []
    for e in eps:
        for i, run in enumerate(runs):
            floor = cell(rows, "bpe_human", run, "16", "train", e, "heldout_bits_per_nt")
            c_own, c_fresh = bhcell(e, "r=0/train", i), bhcell(e, "r=0/fresh", i)
            for host, v in (("own", c_own), ("fresh", c_fresh)):
                if v:
                    nonzero.append((e, i, host, v))
            lines.append(
                f"{('round~' + e if e != 'final' else 'final') if i == 0 else ''} & {i} & "
                f"{'---' if floor is None else f'{floor:.3f}'} & "
                f"{two(cell(rows, 'bpe_human', run, '16', 'train', e, 'rank1_rate'))} & "
                f"{two(bhcell(e, 'r=1/train', i))} & "
                f"{two(bhcell(e, 'r=1/fresh', i))} & "
                f"{two(c_own)} & {two(c_fresh)} & "
                f"{pct(cell(rows, 'bpe_human', run, '16', 'train', e, 'exact_rate'))} & "
                f"{pct(cell(rows, 'bpe_human', run, '1', 'train', e, 'exact_rate'))} \\\\")
        lines.append("\\addlinespace[2pt]")
    # A list of thirteen cells is unreadable in a table footer and is not the quantity anyone
    # needs. What the control has to establish is that no cell is large and that the hits are a
    # few records rather than a rate, so the footer says the maximum, the count of non-zero cells
    # and where the distinct-record count comes from.
    n_cells = 2 * len(eps) * len(runs)
    if not nonzero:
        note = "every control cell is $0.00$"
    else:
        hi = max(v for _, _, _, v in nonzero)
        note = (f"{len(nonzero)} of the {n_cells} control cells are non-zero, none above "
                f"${hi:.2f}$; \\texttt{{pilot2/count\\_control\\_hits.py}} gives the distinct "
                f"records behind them")
    lines += ["\\midrule",
              "\\multicolumn{10}{l}{\\footnotesize 50 records per cell. " + note + ".} \\\\",
              "\\bottomrule", "\\end{tabular}"]
    (out / "a4_ident_perseed.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("  a4_ident_perseed.tex")


# ---------------------------------------------------------------- A5
def series(rows, group, run, tier="16", host="train", drop_final=True):
    pts = [(float(r["heldout_bits_per_nt"]), float(r["exact_rate"])) for r in rows
           if r["group"] == group and r["run"] == run and r["tier"] == tier
           and r["host"] == host and not (drop_final and r["epoch"] == "final")]
    return sorted(pts)


def at(pts, target):
    if not pts or not (pts[0][0] <= target <= pts[-1][0]):
        return None
    for (f0, r0), (f1, r1) in zip(pts, pts[1:]):
        if f0 <= target <= f1:
            return r0 if f1 == f0 else r0 + (target - f0) / (f1 - f0) * (r1 - r0)
    return None


def cost_of_full(pts, thresh=0.99):
    for floor, rate in pts:
        if rate >= thresh:
            return floor
    return None


def table_kcurve(rows, out: Path):
    """The sweep per seed, both windows: the cells behind the means in Table 4."""
    lines = [head("A5: tokenizer sweep at matched held-out loss, per seed, both windows."),
             "\\begin{tabular}{llccccccc}", "\\toprule",
             "window & tokenizer & slots & seed & "
             + " & ".join(f"@{t:.2f}" for t in TARGETS) + " & cost of 100\\% \\\\", "\\midrule"]
    for group, wlabel in (("kcurve300", "300\\nt"), ("kcurve", "288\\nt")):
        first_in_window = True
        for tok in TOKS:
            first_in_tok = True
            for sd in (0, 1, 2):
                s = series(rows, group, f"{tok}_ar_s{sd}")
                if not s:
                    continue
                cells = [at(s, t) for t in TARGETS]
                c = cost_of_full(s)
                lines.append(
                    f"{wlabel if first_in_window else ''} & "
                    f"{TOKLAB[tok] if first_in_tok else ''} & "
                    f"{SLOTS[tok]:g} & {sd} & "
                    + " & ".join(pct(x) for x in cells)
                    + f" & {'never' if c is None else f'{c:.2f}'} \\\\")
                first_in_window = first_in_tok = False
            if not first_in_tok:
                lines.append("\\addlinespace[1pt]")
        lines.append("\\midrule")
    lines = lines[:-1] + ["\\bottomrule", "\\end{tabular}"]
    (out / "a5_kcurve_perseed.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("  a5_kcurve_perseed.tex")


