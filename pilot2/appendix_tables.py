def table_capacity(rows, out: Path):
    """Is the tokenizer effect about the size of the embedding table? Read at matched loss."""
    lines = [head("A9: capacity and parametrisation controls at matched held-out loss."),
             "\\begin{tabular}{lcccccc}", "\\toprule",
             "variant & seeds & " + " & ".join(f"@{t:.2f}" for t in TARGETS)
             + " & cost of 100\\% \\\\", "\\midrule"]
    for group, stem, label in CAP:
        per_seed, costs = [], []
        for sd in (0, 1, 2):
            s = series(rows, group, f"{stem}_s{sd}")
            if not s:
                continue
            per_seed.append([at(s, t) for t in TARGETS])
            costs.append(cost_of_full(s))
        if not per_seed:
            continue
        cells = []
        for i in range(len(TARGETS)):
            v = [c[i] for c in per_seed if c[i] is not None]
            cells.append(sum(v) / len(v) if v else None)
        cc = [c for c in costs if c is not None]
        cost = f"{sum(cc) / len(cc):.2f}" if cc else "never"
        lines.append(f"{label} & {len(per_seed)} & " + " & ".join(pct(x) for x in cells)
                     + f" & {cost} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (out / "t_capacity.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("  t_capacity.tex")


