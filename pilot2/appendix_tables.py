def table_rerun(res: Path, out: Path):
    """The nineteen single-basis chromosome-22 cells, as the reports record them."""
    rows = []
    for p in sorted(res.glob("*/*/rb_*.md")):
        for line in p.read_text(encoding="utf-8").split("\n"):
            if not line.startswith("| ") or "---" in line or "run |" in line:
                continue
            c = [x.strip().replace("**", "") for x in line.strip("|").split("|")]
            # dispatch on the column count, not on the path: every DNABERT k-mer run directory
            # has "nt" in its name (nt0.05, the mask rate), which sent them all down the NT branch
            # and dropped twelve cells without a word.
            if len(c) == 15:                                       # Nucleotide Transformer
                rows.append((f"{c[0]}, {p.stem[3:]}", c[4], c[5], c[8], c[10], c[11], c[12]))
            elif len(c) == 12:                                     # overlapping k-mers
                rows.append((f"{c[0]}, {p.stem[3:]}", c[4], c[5], "---", c[6], c[8], c[9]))
            elif len(c) == 11:                                     # BPE
                rows.append((f"{c[0]}, {p.stem[3:]}", c[3], c[4], "---", c[5], c[7], c[8]))
    hdr = "run, checkpoint & tier & $n$ & standard & LOO top-1 & ceiling & ours \\\\"
    lines = [head("A7: the 19 single-basis chromosome-22 cells of 23 Oct."),
             "\\begin{longtable}{lcccccc}",
             "\\caption{\\emph{Generated.} The 23 October re-measurement of chromosome~22: "
             "every cell, 50 probes per tier, one host state. \\texttt{standard} is the "
             "prefix-conditioned protocol, which the overlapping-$k$-mer and BPE reports do not "
             "run; \\texttt{ours} is the decoder matched to that vocabulary; $r{=}0$ is the "
             "never-trained control.}\\label{tab:a7}\\\\",
             "\\toprule", hdr, "\\midrule", "\\endfirsthead",
             "\\toprule", hdr, "\\midrule", "\\endhead",
             "\\bottomrule", "\\endlastfoot"]
    for r in sorted(rows):
        lines.append(" & ".join(esc(x) for x in r) + " \\\\")
    lines += ["\\end{longtable}"]
    (out / "a7_rerun.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"  a7_rerun.tex ({len(rows)} rows)")



